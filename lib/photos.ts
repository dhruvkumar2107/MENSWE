export function photo(base: string, w = 900, h?: number): string {
  const params = new URLSearchParams({ auto: "format", fit: "crop", q: "80", w: String(w) });
  if (h) params.set("h", String(h));
  return `${base}?${params.toString()}`;
}

export function photoPool(key: string): string[] {
  const pool = PHOTO_BASE[key];
  return pool && pool.length ? pool : PHOTO_BASE.shirts;
}

